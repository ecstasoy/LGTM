func l2Paths(c Context) []string {
	var out []string
	for _, f := range c.L2Files {
		out = append(out, f.Path)
	}
	return out
}

func TestIsExcluded(t *testing.T) {
	cases := []struct {
		path, patch string
		want        bool
	}{
		{"go.sum", "", true},
		{"frontend/pnpm-lock.yaml", "", true},
		{"web/package-lock.json", "", true},
		{"static/app.min.js", "", true},
		{"api/v1/user.pb.go", "", true},
		{"vendor/github.com/x/y.go", "", true},
		{"pkg/vendor/z.go", "", true},
		{"ui/__snapshots__/a.snap", "", true},
		{"internal/gen/models.go", "@@ -0,0 +1,3 @@\n+// Code generated by sqlc. DO NOT EDIT.\n+package gen\n+", true},
		{"internal/api/review.go", "@@ -1 +1 @@\n-a\n+b", false},
		{"docs/lockfile.md", "", false},
		{"internal/vendors/client.go", "", false},
	}
	for _, c := range cases {
		if got := isExcluded(github.File{Path: c.path, Patch: c.patch}); got != c.want {
			t.Errorf("isExcluded(%q) = %v, want %v", c.path, got, c.want)
		}
	}
}

func TestLayered_ExcludesLockfilesFromL2(t *testing.T) {
	b := NewLayeredBuilder()
	pr := newPR([]github.File{
		{Path: "main.go", Status: "modified", Patch: "@@ -1 +1 @@\n-a\n+b"},
		{Path: "go.sum", Status: "modified", Patch: strings.Repeat("+h1:xyz\n", 50)},
	})
	ctx, err := b.Build(context.Background(), pr)
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	if paths := l2Paths(ctx); contains(paths, "go.sum") || !contains(paths, "main.go") {
		t.Errorf("L2 = %v, want main.go only", paths)
	}
	if !contains(ctx.BudgetReport.Excluded, "go.sum") {
		t.Errorf("Excluded = %v, want go.sum", ctx.BudgetReport.Excluded)
	}
	if len(ctx.BudgetReport.Dropped) != 0 {
		t.Errorf("excluded files must not count as dropped: %v", ctx.BudgetReport.Dropped)
	}
	if !strings.Contains(ctx.L1Meta, "- go.sum") {
		t.Errorf("L1 should still list excluded files: %q", ctx.L1Meta)
	}
}

